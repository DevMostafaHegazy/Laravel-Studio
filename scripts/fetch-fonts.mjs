import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const styleDir = path.join(root, 'extensions', 'laravel-tools', 'src', 'browser', 'style');
const licenseDir = path.join(root, 'licenses');
const fonts = [
    {
        family: 'Inter',
        weight: '100 900',
        style: 'normal',
        url: 'https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@5.3.0/files/inter-latin-wght-normal.woff2',
        license: 'Inter-OFL.txt',
        licenseUrl: 'https://cdn.jsdelivr.net/npm/@fontsource-variable/inter@5.3.0/LICENSE'
    },
    {
        family: 'JetBrains Mono',
        weight: '100 800',
        style: 'normal',
        url: 'https://cdn.jsdelivr.net/npm/@fontsource-variable/jetbrains-mono@5.3.0/files/jetbrains-mono-latin-wght-normal.woff2',
        license: 'JetBrains-Mono-OFL.txt',
        licenseUrl: 'https://cdn.jsdelivr.net/npm/@fontsource-variable/jetbrains-mono@5.3.0/LICENSE'
    }
];

fs.mkdirSync(styleDir, { recursive: true });
fs.mkdirSync(licenseDir, { recursive: true });

const faces = [];
for (const font of fonts) {
    process.stdout.write(`Fetching ${font.family}… `);
    const response = await fetch(font.url);
    if (!response.ok) {
        throw new Error(`${response.status} ${response.statusText} for ${font.url}`);
    }
    const bytes = Buffer.from(await response.arrayBuffer());
    const base64 = bytes.toString('base64');
    const licenseResponse = await fetch(font.licenseUrl);
    if (licenseResponse.ok) {
        fs.writeFileSync(path.join(licenseDir, font.license), await licenseResponse.text());
    }
    faces.push(`@font-face {
    font-family: '${font.family}';
    font-style: ${font.style};
    font-weight: ${font.weight};
    font-display: swap;
    src: url('data:font/woff2;base64,${base64}') format('woff2-variations');
}`);
    process.stdout.write(`${(bytes.length / 1024).toFixed(0)} KB embedded\n`);
}

fs.writeFileSync(
    path.join(styleDir, 'fonts.css'),
    `/* Generated by scripts/fetch-fonts.mjs. Fonts are licensed under the SIL Open Font License 1.1. */\n${faces.join('\n\n')}\n`,
    'utf8'
);
console.log(`Wrote ${path.relative(root, path.join(styleDir, 'fonts.css'))}`);
